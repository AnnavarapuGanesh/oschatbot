
import os
import time
from pathlib import Path

import streamlit as st
from dotenv import load_dotenv
from pinecone import Pinecone
from pinecone_text.sparse import BM25Encoder
from duckduckgo_search import DDGS
from sentence_transformers import SentenceTransformer
from groq import Groq

# ==========================================
# 1. STREAMLIT CONFIGURATION
# ==========================================

st.set_page_config(
    page_title="OS RAG Chatbot",
    page_icon="💻",
    layout="wide"
)

st.title("💻 Operating Systems Expert Chatbot")
st.markdown("Ask anything about Operating Systems.")

BASE_DIR = Path(__file__).resolve().parent

# ==========================================
# 2. LOAD ENVIRONMENT VARIABLES AND SECRETS
# ==========================================

load_dotenv(BASE_DIR / ".env")


def get_config(key, default=None):
    value = os.getenv(key)

    if value:
        return value

    try:
        return st.secrets.get(key, default)
    except Exception:
        return default


GROQ_API_KEY = get_config("GROQ_API_KEY")
PINECONE_API_KEY = get_config("PINECONE_API_KEY")
PINECONE_INDEX_NAME = get_config(
    "PINECONE_INDEX_NAME",
    "os-rag-chatbot"
)

LLM_MODEL = "llama-3.3-70b-versatile"

# Check API keys before initializing resources
if not GROQ_API_KEY or not PINECONE_API_KEY:
    st.error(
        "Missing API credentials. "
        "Configure GROQ_API_KEY and PINECONE_API_KEY "
        "in Streamlit Cloud Secrets."
    )
    st.stop()

# ==========================================
# 3. INITIALIZE GROQ
# ==========================================

try:
    client = Groq(api_key=GROQ_API_KEY)
except Exception as e:
    st.error(f"Groq initialization failed: {e}")
    st.stop()

# ==========================================
# 4. PINECONE INITIALIZATION
# ==========================================

@st.cache_resource(show_spinner=False)
def get_pinecone_index(api_key, index_name):
    pc = Pinecone(api_key=api_key)
    return pc.Index(index_name)


try:
    with st.spinner("Connecting to Pinecone..."):
        index = get_pinecone_index(
            PINECONE_API_KEY,
            PINECONE_INDEX_NAME
        )

except Exception as e:
    st.error(f"Pinecone connection failed: {e}")
    st.stop()


# ==========================================
# 5. BM25 INITIALIZATION
# ==========================================

@st.cache_resource(show_spinner=False)
def get_bm25():
    bm25_path = BASE_DIR / "bm25_params.json"

    if not bm25_path.exists():
        raise FileNotFoundError(
            "bm25_params.json not found. "
            "Upload the file generated by ingest.py to GitHub."
        )

    bm25_model = BM25Encoder()
    bm25_model.load(str(bm25_path))

    return bm25_model


try:
    bm25 = get_bm25()

except Exception as e:
    st.error(f"BM25 initialization failed: {e}")
    st.stop()


# ==========================================
# 6. EMBEDDING MODEL
# ==========================================

@st.cache_resource(show_spinner=False)
def get_embedding_model():
    return SentenceTransformer("all-MiniLM-L6-v2")


try:
    with st.spinner("Loading embedding model..."):
        embedding_model = get_embedding_model()

except Exception as e:
    st.error(f"Embedding model loading failed: {e}")
    st.stop()


# ==========================================
# 7. HYBRID SEARCH
# ==========================================

def hybrid_score(dense, sparse, alpha=0.75):

    dense_scaled = [
        float(v) * alpha for v in dense
    ]

    sparse_scaled = {
        "indices": sparse["indices"],
        "values": [
            float(v) * (1 - alpha)
            for v in sparse["values"]
        ]
    }

    return dense_scaled, sparse_scaled


# ==========================================
# 8. WEB SEARCH FALLBACK
# ==========================================

def web_search(query):

    try:
        results = DDGS().text(
            query,
            max_results=3
        )

        results = list(results or [])

        if not results:
            return "", []

        context_parts = []
        sources = []

        for result in results:
            body = result.get("body", "")
            href = result.get("href", "")

            if body:
                context_parts.append(
                    f"{body}\nSource: {href}"
                )

            if href:
                sources.append(href)

        return "\n\n".join(context_parts), sources

    except Exception as e:
        return f"Web search error: {e}", []


# ==========================================
# 9. GROQ ANSWER GENERATION
# ==========================================

def generate_answer(context, query):

    if not context.strip():
        return "Not found in knowledge base."

    prompt = f"""
You are an expert Operating Systems tutor.

Answer the user's question using the provided context.

Instructions:
1. Explain concepts in simple English.
2. Use examples wherever useful.
3. Answer only using the provided context.
4. If the answer is unavailable, say:
   Not found in knowledge base.
5. Do not invent technical information.

Context:
{context}

Question:
{query}

Answer:
"""

    try:
        response = client.chat.completions.create(
            model=LLM_MODEL,
            messages=[
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            temperature=0.3,
            max_tokens=512
        )

        return response.choices[0].message.content or "No answer generated."

    except Exception as e:
        return f"Groq Error: {e}"


# ==========================================
# 10. SESSION STATE
# ==========================================

if "messages" not in st.session_state:
    st.session_state.messages = []

if "fallback" not in st.session_state:
    st.session_state.fallback = None


# ==========================================
# 11. DISPLAY PREVIOUS CHAT
# ==========================================

for msg in st.session_state.messages:

    with st.chat_message(msg["role"]):

        st.markdown(msg["content"])

        if msg.get("sources"):

            with st.expander("Sources"):

                for source in msg["sources"]:
                    st.write(source)


# ==========================================
# 12. WEB SEARCH FALLBACK
# ==========================================

if st.session_state.fallback:

    st.warning(
        "Answer not found in the knowledge base. "
        "Would you like to search the web?"
    )

    col1, col2 = st.columns(2)

    with col1:

        if st.button("Yes, search web"):

            query = st.session_state.fallback

            with st.spinner("Searching the web..."):

                web_context, web_sources = web_search(query)

                if not web_context:
                    st.error("No web results found.")

                else:
                    answer = generate_answer(
                        web_context,
                        query
                    )

                    st.session_state.messages.append({
                        "role": "assistant",
                        "content": answer,
                        "sources": web_sources
                    })

            st.session_state.fallback = None
            st.rerun()

    with col2:

        if st.button("No, skip"):

            st.session_state.fallback = None
            st.rerun()


# ==========================================
# 13. USER INPUT AND CHAT PROCESSING
# ==========================================

if query := st.chat_input("Ask anything about Operating Systems..."):

    st.session_state.messages.append({
        "role": "user",
        "content": query
    })

    with st.chat_message("user"):
        st.markdown(query)

    with st.chat_message("assistant"):

        start_time = time.time()

        try:

            # Dense embedding generation
            dense = embedding_model.encode(
                [query]
            )[0].tolist()

            # Sparse BM25 query
            sparse = bm25.encode_queries([query])[0]

            # Hybrid scoring
            hybrid_dense, hybrid_sparse = hybrid_score(
                dense,
                sparse
            )

            # Pinecone retrieval
            response = index.query(
                vector=hybrid_dense,
                sparse_vector=hybrid_sparse,
                top_k=5,
                include_metadata=True
            )

            contexts = []
            sources = []

            # Extract matching documents
            for match in response["matches"]:

                metadata = match.get("metadata") or {}

                text = metadata.get("text")

                if not text:
                    continue

                contexts.append(text)

                source = metadata.get(
                    "source",
                    "Unknown source"
                )

                score = match.get("score", 0)

                sources.append(
                    f"{source} (Score: {score:.2f})"
                )

            # No relevant documents found
            if not contexts:

                st.session_state.fallback = query

                st.info(
                    "No matching documents found. "
                    "Web search fallback is available."
                )

                st.rerun()

            # Combine retrieved context
            context_text = "\n\n".join(contexts)

            # Generate answer
            answer = generate_answer(
                context_text,
                query
            )

            # Check whether answer exists
            if "not found in knowledge base" in answer.lower():

                st.session_state.fallback = query

                st.info(
                    "Answer not found in knowledge base."
                )

                st.rerun()

            # Display answer
            st.markdown(answer)

            # Display sources and execution time
            elapsed = time.time() - start_time

            with st.expander(
                f"Sources | Response time: {elapsed:.2f}s"
            ):

                for source in sources:
                    st.write(source)

            # Save assistant response
            st.session_state.messages.append({
                "role": "assistant",
                "content": answer,
                "sources": sources
            })

        except Exception as e:

            st.error(f"Chatbot Error: {e}")
